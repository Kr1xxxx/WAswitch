// 软件界面（侧栏、顶栏、设置、编辑账号）能调用的全部接口。WhatsApp 页面拿不到这些。
const { contextBridge, ipcRenderer } = require('electron');

contextBridge.exposeInMainWorld('wa', {
  onState: (cb) => ipcRenderer.on('state', (_e, s) => cb(s)),
  switchTo: (id) => ipcRenderer.send('switch', id),
  aiAnswer: (yes) => ipcRenderer.send('ai:answer', yes === true),
  add: () => ipcRenderer.send('add'),
  edit: (id) => ipcRenderer.send('edit', id),
  context: (id) => ipcRenderer.send('context', id),
  reload: (id) => ipcRenderer.send('reload', id),
  retry: (id) => ipcRenderer.send('retry', id),
  toggleCollapse: () => ipcRenderer.send('collapse'),
  lock: (on) => ipcRenderer.send('lock', on === true),
  showPage: (page, discard) => ipcRenderer.send('page', page, discard === true),
  remove: (id) => ipcRenderer.send('remove', id),
  editorDirty: (dirty) => ipcRenderer.send('editor:dirty', dirty === true),
  restart: () => ipcRenderer.send('app:restart'),
  setSetting: (key, value) => ipcRenderer.send('setting', { key, value }),
  setMuted: (id, muted) => ipcRenderer.send('mute', { id, muted }),
  netLog: () => ipcRenderer.invoke('netlog:get'),
  netLogClear: () => ipcRenderer.invoke('netlog:clear'),
  panelToggle: (on) => ipcRenderer.send('panel:toggle', typeof on === 'boolean' ? on : null),
  panelTab: (tab) => ipcRenderer.send('panel:tab', tab),
  panelData: () => ipcRenderer.invoke('panel:data'),
  onDock: (cb) => ipcRenderer.on('dock:state', (_e, st) => cb(st)),
  dockGet: () => ipcRenderer.invoke('dock:get'),
  dockItem: (h, fix) => ipcRenderer.invoke('dock:item', { h, fix: fix === true }),
  dockSuggest: (accountId, h, take) => ipcRenderer.invoke('dock:suggest', { accountId, h, take: take === true }),
  dockEdit: (accountId, h, text) => ipcRenderer.invoke('dock:edit', { accountId, h, text }),
  dockAuto: (on) => ipcRenderer.invoke('dock:auto', on === true),
  dockConsent: (kind, ids) => ipcRenderer.invoke('dock:consent', { kind, ids }),
  dockInMode: (id) => ipcRenderer.invoke('dock:inmode', id),
  dockLang: (accountId, title, lang) => ipcRenderer.invoke('dock:lang', { accountId, title, lang }),
  replySave: (data) => ipcRenderer.invoke('reply:save', data),
  replyDelete: (id) => ipcRenderer.invoke('reply:delete', id),
  custSave: (data) => ipcRenderer.invoke('cust:save', data),
  custDelete: (id) => ipcRenderer.invoke('cust:delete', id),
  panelCopy: (text) => ipcRenderer.invoke('panel:copy', text),
  panelInsert: (accountId, text) => ipcRenderer.invoke('panel:insert', { accountId, text }),
  panelExport: (kind, format) => ipcRenderer.invoke('panel:export', { kind, format }),
  panelImport: (kind) => ipcRenderer.invoke('panel:import', { kind }),
  floatToggle: (on) => ipcRenderer.send('float:toggle', typeof on === 'boolean' ? on : null),
  trDailyCap: (n) => ipcRenderer.invoke('tr:dailycap', n),
  trConfig: () => ipcRenderer.invoke('tr:config'),
  trProviderSave: (data) => ipcRenderer.invoke('tr:provider:save', data),
  trProviderDelete: (id) => ipcRenderer.invoke('tr:provider:delete', id),
  trRoles: (primaryId, fallbackId) => ipcRenderer.invoke('tr:roles', { primaryId, fallbackId }),
  trNetwork: (mode, proxyUrl) => ipcRenderer.invoke('tr:network', { mode, proxyUrl }),
  trTest: (id) => ipcRenderer.invoke('tr:test', id),
  trConsent: (ids) => ipcRenderer.invoke('tr:consent', ids),
  trRun: (data) => ipcRenderer.invoke('tr:run', data),
  trCancel: () => ipcRenderer.invoke('tr:cancel'),
  trClipboard: () => ipcRenderer.invoke('tr:clipboard'),
  trChatLang: (accountId) => ipcRenderer.invoke('tr:chatlang', accountId),
  trLang: (accountId, lang) => ipcRenderer.invoke('tr:lang', { accountId, lang }),
  tmodeSave: (data) => ipcRenderer.invoke('tmode:save', data),
  tmodeDelete: (id) => ipcRenderer.invoke('tmode:delete', id),
  notifLog: () => ipcRenderer.invoke('notif:log'),
  notifClear: () => ipcRenderer.invoke('notif:clear'),
  moveAccount: (id, groupId, beforeId) => ipcRenderer.send('acc:move', { id, groupId, beforeId }),
  groupCreate: () => ipcRenderer.send('group:create'),
  groupRename: (id, name) => ipcRenderer.send('group:rename', { id, name }),
  groupToggle: (id) => ipcRenderer.send('group:toggle', id),
  groupContext: (id) => ipcRenderer.send('group:context', id),
  zoom: (id, dir) => ipcRenderer.send('zoom', { id, dir }),
  runCheck: () => ipcRenderer.invoke('check:run'),
  checkFix: (id, region) => ipcRenderer.invoke('check:fix', { id, region }),
  exitAck: (id) => ipcRenderer.invoke('exit:ack', { id }),
  updateCheck: () => ipcRenderer.send('update:check'),
  updateInstall: () => ipcRenderer.send('update:install'),
  openLogs: () => ipcRenderer.send('open-logs'),
  openSource: () => ipcRenderer.send('open-source'),
  editorLoad: (id) => ipcRenderer.invoke('editor:load', id),
  editorTest: (data) => ipcRenderer.invoke('editor:test', data),
  editorSave: (data) => ipcRenderer.invoke('editor:save', data),
  liteOpen: (id, jid) => ipcRenderer.send('lite:open', { id, jid }),
  liteSend: (id, jid, text) => ipcRenderer.invoke('lite:send', { id, jid, text }),
  openLink: (url) => ipcRenderer.send('open-link', url),
  cacheSize: () => ipcRenderer.invoke('cache:size'),
  clearCache: () => ipcRenderer.invoke('cache:clear'),
  memClean: () => ipcRenderer.invoke('mem:clean'),
  teamEnroll: (data) => ipcRenderer.invoke('team:enroll', data),
  teamJoin: (localIds) => ipcRenderer.invoke('team:join', { localIds }),
  teamSync: () => ipcRenderer.invoke('team:sync'),
});
